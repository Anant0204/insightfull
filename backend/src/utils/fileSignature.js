const crypto = require('crypto');
const { JWT_SECRET } = require('../config/env');

const DEFAULT_TTL_SECONDS = 60 * 60; // 1 hour

const computeSignature = (canonicalPath, expires) =>
    crypto.createHmac('sha256', JWT_SECRET).update(`${canonicalPath}:${expires}`).digest('hex');

/**
 * Sign a local /uploads/... URL with a short-lived HMAC signature so private
 * files can be served to <img>/<video> tags without exposing them publicly.
 * Non-local URLs (e.g. Cloudinary) are returned unchanged.
 */
const signLocalUrl = (url, ttlSeconds = DEFAULT_TTL_SECONDS) => {
    if (typeof url !== 'string' || !url.startsWith('/uploads/')) return url;
    const expires = Math.floor(Date.now() / 1000) + ttlSeconds;
    const sig = computeSignature(url, expires);
    return `${url}?exp=${expires}&sig=${sig}`;
};

/**
 * Verify a signature generated by signLocalUrl for the given canonical path.
 */
const verifyFileSignature = (canonicalPath, expires, sig) => {
    if (!canonicalPath || !expires || !sig || typeof sig !== 'string') return false;
    const expNum = parseInt(expires, 10);
    if (!Number.isFinite(expNum) || expNum < Math.floor(Date.now() / 1000)) return false;
    const expected = computeSignature(canonicalPath, expires);
    const sigBuffer = Buffer.from(sig);
    const expectedBuffer = Buffer.from(expected);
    if (sigBuffer.length !== expectedBuffer.length) return false;
    return crypto.timingSafeEqual(sigBuffer, expectedBuffer);
};

/**
 * Convenience: sign imageUrl/videoUrl fields on a record (or array of records)
 * in place, leaving remote URLs untouched.
 */
const signRecordUrls = (record) => {
    if (!record || typeof record !== 'object') return record;
    if (record.imageUrl) record.imageUrl = signLocalUrl(record.imageUrl);
    if (record.screenshotUrl) record.screenshotUrl = signLocalUrl(record.screenshotUrl);
    if (record.videoUrl) record.videoUrl = signLocalUrl(record.videoUrl);
    return record;
};

const signRecordList = (list) => (Array.isArray(list) ? list.map(signRecordUrls) : list);

module.exports = { signLocalUrl, verifyFileSignature, signRecordUrls, signRecordList };
